def _flag_dicts(ev: dict) -> list[dict]:
    req = ev.get("requiredFlags") or []
    return [g for g in req if isinstance(g, dict)]


def _req_attr_gated(ev: dict, attr: str) -> bool:
    spec = (ev.get("requiredAttrs") or {}).get(attr) or {}
    if not isinstance(spec, dict):
        return False
    op = spec.get("operator")
    try:
        val = int(spec.get("value") or 0)
    except (TypeError, ValueError):
        val = 0
    return op in (">=", ">") and val >= 6


def _keep_by(ev: dict, ids: set[int], groups: set[str], jobs: set[str], extra=None) -> bool:
    eid = int(ev["eventId"])
    if eid in ids:
        return True
    cd = set(ev.get("cooldownGroups") or [])
    if cd & groups:
        return True
    if extra and extra(ev, cd):
        return True
    for g in _flag_dicts(ev):
        if g.get("job") in jobs:
            return True
    return False


def _wis_keep(ev: dict) -> bool:
    def extra(ev: dict, cd: set[str]) -> bool:
        if "elder" in cd and int(ev["eventId"]) % 3 == 0:
            return True
        if _req_attr_gated(ev, "wis"):
            return True
        eid = int(ev["eventId"])
        for g in _flag_dicts(ev):
            if g.get("origin") == "priest":
                return True
            if g.get("faith") is True and eid % 2 == 0:
                return True
        return False

    return _keep_by(ev, _KEEP_WIS_IDS, _KEEP_WIS_GROUPS, _KEEP_WIS_JOBS, extra)


def _cha_keep(ev: dict) -> bool:
    def extra(ev: dict, _cd: set[str]) -> bool:
        if _req_attr_gated(ev, "cha"):
            return True
        for g in _flag_dicts(ev):
            if g.get("origin") in {"noble", "street"}:
                return True
        return False

    return _keep_by(ev, _KEEP_CHA_IDS, _KEEP_CHA_GROUPS, _KEEP_CHA_JOBS, extra)


def _clean_fx(fx: dict) -> dict:
    return {k: v for k, v in fx.items() if v}


def _retarget_empty(fx: dict, eid: int, attr: str, into: tuple[str, ...]) -> None:
    bucket = eid % 5
    if bucket == 0:
        return
    if bucket == 4:
        fx[attr] = int(fx.get(attr) or 0) + 1
        return
    dest = into[(bucket - 1) % len(into)]
    fx[dest] = int(fx.get(dest) or 0) + 1


def _trim_attr(ev: dict, fx: dict, orig: dict, attr: str, keep: bool, retarget: str | None) -> None:
    val = int(orig.get(attr) or 0)
    if val <= 0:
        return
    eid = int(ev["eventId"])
    if keep:
        if val >= 2 and eid not in _CLASS_SPIKE_IDS and not _req_attr_gated(ev, attr):
            fx[attr] = 1
        return
    others = [k for k in _PRIMARY_ATTRS if k != attr and int(orig.get(k) or 0) > 0]
    if others:
        fx[attr] = 0
        return
    if val >= 2:
        fx[attr] = 1
        return
    if retarget == "full":
        fx[attr] = 0
        _retarget_empty(fx, eid, attr, ("str", "agi", "con"))
    elif retarget == "mild" and eid % 3 == 0:
        fx[attr] = 0
        _retarget_empty(fx, eid, attr, ("str", "agi", "con"))


def _is_identity_stamp(ev: dict) -> bool:
    eid = int(ev.get("eventId") or 0)
    if 1010 <= eid <= 1190 or 1221 <= eid <= 1270 or 1320 <= eid <= 1369:
        return True
    if 1370 <= eid <= 1499:
        return True
    if 1500 <= eid <= 1535:
        return True
    if 7030 <= eid <= 7199:
        return True
    flags = ev.get("flags") or {}
    if isinstance(flags, dict) and (flags.get("race") or flags.get("origin")):
        return True
    groups = set(ev.get("cooldownGroups") or [])
    if groups & {"heritage", "heritage_set"}:
        return True
    if any(str(g).startswith("hg_") for g in groups):
        return True
    return False


def rebalance_attrs(rows: list[dict]) -> None:
    for ev in rows:
        if ev.get("type") == "death":
            continue
        if _is_identity_stamp(ev):
            continue
        fx = ev.get("effects")
        if not isinstance(fx, dict):
            fx = {}
            ev["effects"] = fx
        orig = {k: int(fx.get(k) or 0) for k in list(fx)}

        _trim_attr(ev, fx, orig, "wis", _wis_keep(ev), retarget="full")
        _trim_attr(ev, fx, orig, "cha", _cha_keep(ev), retarget="mild")

        desc = ev.get("desc") or ""
        groups = set(ev.get("cooldownGroups") or [])
        eid = int(ev["eventId"])
        if (
            groups & _WIS_PENALTY_GROUPS
            or eid in _WIS_PENALTY_IDS
            or any(s in desc for s in _WIS_BLUNT_SNIPPETS)
        ):
            fx["wis"] = int(fx.get("wis") or 0) - 1

        ev["effects"] = _clean_fx(fx)


_IDENTITY_FLAG_KEYS = {"job", "origin", "race"}


def _req_flag_keys(ev: dict) -> set[str]:
    keys: set[str] = set()
    for group in ev.get("requiredFlags") or []:
        if isinstance(group, dict):
            keys.update(group.keys())
    return keys


def _follow_items(ev: dict) -> list[dict]:
    items = ev.get("followUp") or []
    return [x for x in items if isinstance(x, dict)]


def _is_chain_head(ev: dict) -> bool:
    follows = _follow_items(ev)
    if len(follows) >= 2:
        return True
    if any(int(x.get("delay") or 0) > 0 for x in follows):
        return True
    if ev.get("unlockEvents") or ev.get("unlockDelayed"):
        return True
    return False


def _sets_needed_flag(ev: dict, needed: set[str]) -> bool:
    flags = ev.get("flags") or {}
    if not isinstance(flags, dict):
        return False
    return bool(set(flags.keys()) & needed)


def _needed_story_flags(rows: list[dict]) -> set[str]:
    needed: set[str] = set()
    for ev in rows:
        needed |= _req_flag_keys(ev) - _IDENTITY_FLAG_KEYS
    return needed


def _classify_weight_role(ev: dict, needed_story: set[str]) -> str:
    if ev.get("type") in {"forced", "fallback"}:
        return "skip"
    if ev.get("naturalUnlock") is False:
        return "skip"
    if int(ev.get("baseWeight") or 10) <= 0:
        return "skip"
    eid = int(ev.get("eventId") or 0)
    if 1370 <= eid <= 1499:
        return "skip"
    keys = _req_flag_keys(ev)
    has_identity = bool(keys & _IDENTITY_FLAG_KEYS)
    has_story = bool(keys - _IDENTITY_FLAG_KEYS)
    has_events = bool(ev.get("requiredEvents"))
    has_attrs = bool(ev.get("requiredAttrs"))
    head = _is_chain_head(ev) or _sets_needed_flag(ev, needed_story)
    if has_identity:
        return "identity"
    if has_story or has_events:
        return "chain"
    if head:
        return "head"
    if has_attrs:
        return "attr"
    return "flavor"


def _apply_weight(ev: dict, factor: float, floor: int, cap: int) -> None:
    raw = ev.get("baseWeight")
    w = 10 if raw is None else int(raw)
    if w <= 0:
        return
    nxt = int(round(w * factor))
    nxt = max(floor, min(cap, nxt))
    ev["baseWeight"] = max(1, nxt)


def reweight_story(rows: list[dict]) -> None:
    """Favor job/origin/chain beats over ungated flavor in the yearly random draw."""
    needed_story = _needed_story_flags(rows)
    counts: dict[str, list[tuple[int, int]]] = {}
    policy = {
        "flavor": (0.4, 1, 3),
        "identity": (2.1, 12, 26),
        "chain": (1.9, 12, 26),
        "head": (1.7, 10, 24),
        "attr": (1.25, 8, 22),
    }
    for ev in rows:
        role = _classify_weight_role(ev, needed_story)
        if role == "skip" or role not in policy:
            continue
        before = 10 if ev.get("baseWeight") is None else int(ev.get("baseWeight") or 0)
        factor, floor, cap = policy[role]
        _apply_weight(ev, factor, floor, cap)
        counts.setdefault(role, []).append((before, int(ev["baseWeight"])))
    parts = []
    for role in ("flavor", "identity", "chain", "head", "attr"):
        pairs = counts.get(role) or []
        if not pairs:
            continue
        b = sum(p[0] for p in pairs) / len(pairs)
        a = sum(p[1] for p in pairs) / len(pairs)
        parts.append(f"{role} {len(pairs)} {b:.1f}→{a:.1f}")
    if parts:
        print("reweight " + ", ".join(parts))


