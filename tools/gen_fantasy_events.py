def _group_primaries(group: dict) -> set[str]:
    out: set[str] = set()
    job = group.get("job")
    origin = group.get("origin")
    if isinstance(job, str) and job in JOB_PRIMARY:
        out.update(JOB_PRIMARY[job])
    if isinstance(origin, str) and origin in ORIGIN_PRIMARY:
        out.update(ORIGIN_PRIMARY[origin])
    return out


def _high_attr_keys(ev: dict) -> set[str]:
    out: set[str] = set()
    req = ev.get("requiredAttrs") or {}
    if not isinstance(req, dict):
        return out
    for key, spec in req.items():
        if key not in _STAT_KEYS or not isinstance(spec, dict):
            continue
        op = spec.get("operator")
        try:
            val = int(spec.get("value") or 0)
        except (TypeError, ValueError):
            val = 0
        if op in (">=", ">") and val >= 5:
            out.add(key)
    return out


def _event_primaries(ev: dict) -> tuple[str, ...]:
    groups = _flag_dicts(ev)
    flag_sets = [_group_primaries(g) for g in groups]
    flag_sets = [s for s in flag_sets if s]
    from_flags: set[str] = set()
    if len(flag_sets) == 1:
        from_flags = flag_sets[0]
    elif len(flag_sets) > 1:
        shared = set.intersection(*flag_sets)
        if shared:
            from_flags = shared
    from_flags |= _high_attr_keys(ev)
    return tuple(k for k in _STAT_KEYS if k in from_flags)


def _pos(fx: dict, key: str) -> int:
    return max(0, int(fx.get(key) or 0))


def _pick_primary(fx: dict, primaries: tuple[str, ...], eid: int) -> str:
    ranked = sorted(primaries, key=lambda k: (_pos(fx, k), primaries.index(k)))
    return ranked[eid % len(ranked)]


def _pick_donor(fx: dict, primaries: tuple[str, ...]) -> str | None:
    offs = [k for k in _DONOR_ORDER if k not in primaries and _pos(fx, k) > 0]
    return offs[0] if offs else None


def _should_bias(eid: int, has_primary: bool, donor: str | None, fx: dict) -> str | None:
    """Return 'convert' | 'add' | None. Intentionally not all events."""
    if has_primary and donor:
        if donor == "gold" and eid % 3 != 0:
            return None
        return "convert" if eid % 5 >= 2 else None
    if not has_primary and donor:
        if donor == "gold" and eid % 2 == 0:
            return None
        return "convert" if eid % 10 >= 3 else None
    if not has_primary and not donor:
        if any(int(fx.get(k) or 0) < 0 for k in _STAT_KEYS):
            return None
        return "add"
    return None


def _skip_primary_bias(ev: dict) -> bool:
    if ev.get("type") in {"death", "forced", "fallback"}:
        return True
    eid = int(ev.get("eventId") or 0)
    if 1010 <= eid <= 1190 or 1221 <= eid <= 1270:
        return True
    if 1370 <= eid <= 1499 or 1500 <= eid <= 1535:
        return True
    if 1610 <= eid <= 1621:
        return True
    return False


def bias_primary_rewards(rows: list[dict]) -> None:
    """Nudge job/origin/high-attr events toward their main stats, not exclusively."""
    touched = 0
    scanned = 0
    before_on = before_all = after_on = after_all = 0
    for ev in rows:
        if _skip_primary_bias(ev):
            continue
        primaries = _event_primaries(ev)
        if not primaries:
            continue
        fx = ev.get("effects")
        if not isinstance(fx, dict):
            fx = {}
            ev["effects"] = fx
        scanned += 1
        pre_all = sum(_pos(fx, k) for k in _STAT_KEYS)
        pre_on = sum(_pos(fx, k) for k in primaries)
        before_all += pre_all
        before_on += pre_on
        has_primary = pre_on > 0
        donor = _pick_donor(fx, primaries)
        action = _should_bias(int(ev["eventId"]), has_primary, donor, fx)
        if action == "convert" and donor:
            dest = _pick_primary(fx, primaries, int(ev["eventId"]))
            fx[donor] = int(fx.get(donor) or 0) - 1
            fx[dest] = int(fx.get(dest) or 0) + 1
            touched += 1
        elif action == "add":
            dest = _pick_primary(fx, primaries, int(ev["eventId"]))
            fx[dest] = int(fx.get(dest) or 0) + 1
            touched += 1
        ev["effects"] = _clean_fx(fx)
        after_all += sum(_pos(ev["effects"], k) for k in _STAT_KEYS)
        after_on += sum(_pos(ev["effects"], k) for k in primaries)
