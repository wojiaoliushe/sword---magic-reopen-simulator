events: list[dict] = []
ids: set[int] = set()


def add(event: dict) -> None:
    eid = int(event["eventId"])
    if eid in ids:
        raise ValueError(f"duplicate eventId {eid}")
    event["eventId"] = eid
    ids.add(eid)
    events.append(event)


def job_req(*jobs: str) -> list[dict]:
    return [{"job": j} for j in jobs]


def race_req(*races: str) -> list[dict]:
    return [{"race": r} for r in races]


def origin_req(*origins: str) -> list[dict]:
    return [{"origin": o} for o in origins]


def w_attr(attr: str, base: int = 5, multiplier: int = 2, min_factor: float | None = None) -> dict:
    item: dict = {"attr": attr, "base": base, "multiplier": multiplier}
    if min_factor is not None:
        item["minFactor"] = min_factor
    return item


