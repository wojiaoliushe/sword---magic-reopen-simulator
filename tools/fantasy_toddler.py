# -*- coding: utf-8 -*-
"""Pre-school years: delay0 vignettes hung on forced year markers.

Ages 1/3/4 are forced-only, so a random childhood pool never fires there.
Infant (1–2) and toddler (3–5) scenes are naturalUnlock=false and picked as
delay0 follow-ups. Most have no effects; a few set small attrs or flags.
"""
from __future__ import annotations


def _d0(*eids: int) -> list[dict]:
    return [{"eventId": i, "delay": 0} for i in eids]


def _scene(
    add,
    eid: int,
    desc: str,
    *,
    min_age: int,
    max_age: int,
    weight: int = 12,
    effects: dict | None = None,
    flags: dict | None = None,
    required: list | None = None,
    mutex: list | None = None,
) -> None:
    ev = {
        "eventId": eid,
        "desc": desc,
        "minAge": min_age,
        "maxAge": max_age,
        "baseWeight": weight,
        "naturalUnlock": False,
        "maxTriggers": 1,
    }
    if effects:
        ev["effects"] = effects
    if flags:
        ev["flags"] = flags
    if required:
        ev["requiredFlags"] = required
    if mutex:
        ev["mutexEvents"] = mutex
    add(ev)


def apply_toddler(events, add) -> None:
    infant_ids = _add_infant(add)
    toddler_ids = _add_toddler(add)

    for ev in events:
        if ev["eventId"] == 1201:
            ev["followUp"] = _d0(*infant_ids)
        elif ev["eventId"] == 1202:
            ev["followUp"] = _d0(*toddler_ids)

    add({
        "eventId": 1204,
        "type": "forced",
        "desc": "你开始试着把世界从爬改成走。摔是学费，尘土是收据。",
        "minAge": 2,
        "maxAge": 2,
        "baseWeight": 0,
        "followUp": _d0(*infant_ids),
    })
    add({
        "eventId": 1205,
        "type": "forced",
        "desc": "你已经能把椅子当成山。大人说你明年要学规矩，你把这句话当成山的另一种叫法。",
        "minAge": 5,
        "maxAge": 5,
        "baseWeight": 0,
        "followUp": _d0(*toddler_ids),
    })


