def split_weight(total: int, n: int) -> list[int]:
    total = int(total)
    if n <= 0:
        return []
    if total < n:
        return [1] * n
    base, rem = divmod(total, n)
    return [base + (1 if i < rem else 0) for i in range(n)]


def _by_id(events: list[dict], eid: int) -> dict:
    for ev in events:
        if ev["eventId"] == eid:
            return ev
    raise KeyError(eid)


def _expand_group(events, add, core_map, lines_map, next_id: int) -> int:
    for key, core_id in core_map.items():
        src = _by_id(events, core_id)
        lines = lines_map[key]
        weights = split_weight(int(src.get("baseWeight", 10)), len(lines))
        src["desc"] = lines[0]
        src["baseWeight"] = weights[0]
        for i, line in enumerate(lines[1:], 1):
            ev = copy.deepcopy(src)
            ev["eventId"] = next_id
            ev["desc"] = line
            ev["baseWeight"] = weights[i]
            add(ev)
            next_id += 1
    return next_id


